// הסימן שלפיו מזהים שבקוד שהודבק כבר יש שכבת דיווח.
export const REPORT_MARKER = /rezef\s*\.\s*(answer|finish)\s*\(|rezef-report/;

export function hasReporting(html: string): boolean {
  return REPORT_MARKER.test(html);
}

export const REPORT_SNIPPET = `<script>
/* rezef-report v1 */
window.rezef = (function () {
  function send(type, data) {
    try { window.parent.postMessage({ rezef: 1, type: type, data: data || {} }, "*"); } catch (e) {}
  }
  return {
    start: function (d) { send("start", d); },
    answer: function (d) { send("answer", d); },
    progress: function (percent) { send("progress", { percent: percent }); },
    finish: function (d) { send("finish", d); }
  };
})();
</script>`;

